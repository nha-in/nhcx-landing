/*
 * "What each side gets": one bundle, every payer. The hospital sends its
 * claim to NHCX, and from there it reaches PM-JAY (the page's orange), a
 * state scheme (blue) or a private payer (green), each on its own line; a
 * payer's box glows as its claim arrives. The dots are SVG motion paths, so
 * they follow the corners at any size, and they are hidden under reduced
 * motion (styles/pmjay.css).
 */
const CYCLE = 2.4;
const PAYER_LOOK = [
  { color: '#F26B21', tint: '#FAD5C0', y: 66, leg: 'H306V66H350', box: { fill: '#FFFBF7', stroke: '#F3DCCB', text: '#B24E18' } },
  { color: '#1F4EE0', tint: '#CDD8FB', y: 149, leg: 'H350', box: { fill: '#ffffff', stroke: '#E4E8F1', text: '#3E4759' } },
  { color: '#0F9D58', tint: '#C3EAD5', y: 232, leg: 'H306V232H350', box: { fill: '#ffffff', stroke: '#E4E8F1', text: '#3E4759' } },
];

export function SidesArt({ hospital, hub, hubNote, payers }: { hospital: string; hub: string; hubNote: string; payers: string[] }) {
  return (
    <svg viewBox="0 0 460 300" width="100%" className="pj-art" aria-hidden="true">
      <path d="M56 24V276M226 24V276M399 24V276" stroke="#F2F4F8" strokeWidth="1" />
      <path d="M102 149H186" fill="none" stroke="#E3E7F0" strokeWidth="1.6" strokeLinecap="round" />
      {PAYER_LOOK.map((look) => (
        <path key={look.color} d={`M266 149${look.leg}`} fill="none" stroke={look.tint} strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" />
      ))}

      {PAYER_LOOK.map((look, i) => {
        const begin = `${(i * CYCLE) / PAYER_LOOK.length}s`;
        return (
          <circle key={look.color} className="pj-art-pkt" r="5" fill={look.color} opacity="0">
            <animateMotion dur={`${CYCLE}s`} begin={begin} repeatCount="indefinite" calcMode="linear" keyPoints="0;1;1" keyTimes="0;0.78;1" path={`M102 149H266${look.leg}`} />
            <animate attributeName="opacity" dur={`${CYCLE}s`} begin={begin} repeatCount="indefinite" values="0;1;1;0;0" keyTimes="0;0.06;0.72;0.8;1" />
          </circle>
        );
      })}

      <rect x="10" y="120" width="92" height="58" rx="9" fill="#ffffff" stroke="#E4E8F1" strokeWidth="1.3" />
      <rect x="44" y="138" width="24" height="22" rx="3" fill="#ffe4d3" strokeWidth="1.2" style={{ stroke: 'var(--blue)' }} />
      <path d="M56 144v10M51 149h10" strokeWidth="1.4" strokeLinecap="round" style={{ stroke: 'var(--blue)' }} />
      <text x="56" y="196" textAnchor="middle" className="pj-art-note">
        {hospital}
      </text>

      <rect x="186" y="122" width="80" height="54" rx="9" fill="#ffffff" stroke="#f6c9b0" strokeWidth="1.3" />
      <text x="226" y="153" textAnchor="middle" className="pj-art-hub">
        {hub}
      </text>
      <text x="226" y="196" textAnchor="middle" className="pj-art-mono">
        {hubNote}
      </text>

      {PAYER_LOOK.map((look, i) => (
        <g key={look.color}>
          <rect className="pj-art-ring" x="345" y={look.y - 22} width="108" height="44" rx="11" fill="none" stroke={look.color} strokeWidth="1.5" opacity="0">
            <animate attributeName="opacity" dur={`${CYCLE}s`} begin={`${(i * CYCLE) / PAYER_LOOK.length}s`} repeatCount="indefinite" values="0;0;0.9;0" keyTimes="0;0.74;0.82;1" />
          </rect>
          <rect x="350" y={look.y - 17} width="98" height="34" rx="8" fill={look.box.fill} stroke={look.box.stroke} strokeWidth="1.3" />
          <text x="399" y={look.y + 4} textAnchor="middle" className="pj-art-label" style={{ fill: look.box.text }}>
            {payers[i]}
          </text>
        </g>
      ))}
    </svg>
  );
}
